    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // Guardamos un objeto Terreno usando las cajas de texto.
        try {
            String numero = this.txtNumTerreno.getText().trim();
            if (numero.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Escribe el número del terreno.");
                return;
            }

            float ancho = Float.parseFloat(this.txtAncho.getText().trim());
            float largo = Float.parseFloat(this.txtLargo.getText().trim());
            if (!Float.isFinite(ancho) || !Float.isFinite(largo) || ancho <= 0 || largo <= 0) {
                JOptionPane.showMessageDialog(this, "Ancho y Largo deben ser mayores que cero.");
                return;
            }

            terreno.setNumTerreno(numero);
            terreno.setAncho(ancho);
            terreno.setLargo(largo);
            terrenoGuardado = true;

            JOptionPane.showMessageDialog(this, "Se guardó el objeto Terreno con éxito.");
            this.limpiar();
            this.deshabilitar();
            this.btnGuardar.setEnabled(false);
            this.btnMostrar.setEnabled(true);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Escribe números válidos en Ancho y Largo.",
                    "Datos incorrectos", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        // Mostramos los datos y calculamos el area y el perimetro.
        if (!terrenoGuardado) {
            JOptionPane.showMessageDialog(this, "Primero guarda un terreno.");
            return;
        }
        this.txtNumTerreno.setText(terreno.getNumTerreno());
        this.txtAncho.setText(String.valueOf(terreno.getAncho()));
        this.txtLargo.setText(String.valueOf(terreno.getLargo()));
        this.txtPerimetro.setText(String.valueOf(terreno.calcularPerimetro()));
        this.txtArea.setText(String.valueOf(terreno.calcularArea()));
        this.deshabilitar();
        this.btnGuardar.setEnabled(false);
        // Listo.
    }//GEN-LAST:event_btnMostrarActionPerformed

